#!/bin/bash
# Run all JMH benchmarks and generate a markdown dashboard.
#
# Usage:
#   ./scripts/run_benchmarks.sh              # full run (all benchmarks)
#   ./scripts/run_benchmarks.sh --quick      # fast run (fewer iterations)
#   ./scripts/run_benchmarks.sh --competitor # competitor benchmarks only
#
# Output:
#   docs/benchmarks/DASHBOARD.md             # formatted markdown dashboard
#   docs/benchmarks/results/YYYY-MM-DD.txt   # raw JMH output

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
GRADLEW="${REPO_ROOT}/gradlew"
RESULTS_DIR="${REPO_ROOT}/docs/benchmarks/results"
DASHBOARD="${REPO_ROOT}/docs/benchmarks/DASHBOARD.md"
TODAY=$(date +%Y-%m-%d)
RAW_OUTPUT="${RESULTS_DIR}/${TODAY}.txt"

# ── Parse flags ───────────────────────────────────────────────────────────────

QUICK=false
COMPETITOR_ONLY=false

for arg in "$@"; do
    case "$arg" in
        --quick)      QUICK=true ;;
        --competitor) COMPETITOR_ONLY=true ;;
        *) echo "Unknown flag: $arg"; exit 1 ;;
    esac
done

if [ "$QUICK" = true ]; then
    JMH_ARGS="-wi 1 -i 2 -f 1 -t 1"
else
    JMH_ARGS="-wi 3 -i 5 -f 1 -t 1"
fi

# ── Helpers ───────────────────────────────────────────────────────────────────

step() { echo; echo "==> $*"; }

require_java() {
    "${REPO_ROOT}/scripts/require_java21.sh"
}

format_integer() {
    local number="$1"
    local result=""

    while [ "${#number}" -gt 3 ]; do
        result=",${number: -3}${result}"
        number="${number:0:${#number}-3}"
    done

    printf "%s%s" "${number}" "${result}"
}

format_score() {
    local lines="$1"
    local benchmark="$2"
    local batch_size="${3:-}"
    local score

    if [ -n "${batch_size}" ]; then
        score=$(awk -v benchmark="${benchmark}" -v batch_size="${batch_size}" \
            '$1 == benchmark && $2 == batch_size { printf "%d", $6; found = 1; exit } END { if (!found) exit 1 }' <<< "${lines}")
    else
        score=$(awk -v benchmark="${benchmark}" \
            '$1 == benchmark { printf "%d", $6; found = 1; exit } END { if (!found) exit 1 }' <<< "${lines}")
    fi

    format_integer "${score}"
}

# ── Run benchmarks ────────────────────────────────────────────────────────────

require_java
mkdir -p "${RESULTS_DIR}"

if [ "$COMPETITOR_ONLY" = true ]; then
    BENCH_FILTER="Competitor"
else
    BENCH_FILTER="io.github.frikit.krandom.benchmarks"
fi

step "Compiling benchmarks"
"${GRADLEW}" :benchmarks:classes --console=plain -q

step "Running JMH benchmarks (filter=${BENCH_FILTER})"
echo "  JMH args: ${JMH_ARGS}"
echo "  This may take several minutes..."
echo

"${GRADLEW}" :benchmarks:jmh -PjmhArgs="${BENCH_FILTER} ${JMH_ARGS}" \
    --console=plain 2>&1 | tee "${RAW_OUTPUT}"

step "Raw output saved to ${RAW_OUTPUT}"

# ── Parse results and generate dashboard ──────────────────────────────────────

step "Generating dashboard"

# Extract JDK version
JDK_VERSION=$(java -version 2>&1 | head -1 | sed 's/.*"\(.*\)".*/\1/')
ARCH=$(uname -m)
OS=$(uname -s)
OS_VERSION=$(uname -r)

# Extract the benchmark results table from JMH output
JMH_TABLE=$(grep -E "^(Benchmark|Competitor|Expanded|FirstName|ObjectFactory|ObjectGenerator|Regex|Schema)" "${RAW_OUTPUT}" 2>/dev/null || true)

if [ -z "${JMH_TABLE}" ]; then
    echo "WARNING: no JMH result rows parsed from ${RAW_OUTPUT}; the generated dashboard will have empty tables." >&2
    echo "         Check the raw output for JMH failures or a changed output format." >&2
fi

# Build the dashboard
cat > "${DASHBOARD}" << HEADER
# krandom Benchmark Dashboard

> Auto-generated by \`scripts/run_benchmarks.sh\` on ${TODAY}.
> Re-run the script to refresh with current numbers.

## Environment

| Property | Value |
|:---|:---|
| Date | ${TODAY} |
| JDK | ${JDK_VERSION} |
| Architecture | ${ARCH} |
| OS | ${OS} ${OS_VERSION} |
| JMH | 1.37 |
| JMH args | \`${JMH_ARGS}\` |

HEADER

# ── Competitor section ────────────────────────────────────────────────────────

SCALAR_LINES=$(grep "^CompetitorScalar" "${RAW_OUTPUT}" 2>/dev/null || true)
OBJECT_LINES=$(grep "^CompetitorObject" "${RAW_OUTPUT}" 2>/dev/null || true)
BULK_LINES=$(grep "^CompetitorBulk" "${RAW_OUTPUT}" 2>/dev/null || true)

if [ -n "$SCALAR_LINES" ]; then
    # Parse scalar results
    krandom_fn=$(format_score "$SCALAR_LINES" "CompetitorScalarBenchmark.krandomFirstName")
    datafaker_fn=$(format_score "$SCALAR_LINES" "CompetitorScalarBenchmark.dataFakerFirstName")
    javafaker_fn=$(format_score "$SCALAR_LINES" "CompetitorScalarBenchmark.javaFakerFirstName")
    krandom_em=$(format_score "$SCALAR_LINES" "CompetitorScalarBenchmark.krandomEmail")
    datafaker_em=$(format_score "$SCALAR_LINES" "CompetitorScalarBenchmark.dataFakerEmail")
    javafaker_em=$(format_score "$SCALAR_LINES" "CompetitorScalarBenchmark.javaFakerEmail")
    krandom_sa=$(format_score "$SCALAR_LINES" "CompetitorScalarBenchmark.krandomStreetAddress")
    datafaker_sa=$(format_score "$SCALAR_LINES" "CompetitorScalarBenchmark.dataFakerStreetAddress")
    javafaker_sa=$(format_score "$SCALAR_LINES" "CompetitorScalarBenchmark.javaFakerStreetAddress")

    cat >> "${DASHBOARD}" << SCALAR
## Competitor Comparison: Scalar Generation

Single value per invocation (ops/s, higher is better).

| Benchmark | krandom | DataFaker | JavaFaker |
|:---|---:|---:|---:|
| firstName | ${krandom_fn} | ${datafaker_fn} | ${javafaker_fn} |
| email | ${krandom_em} | ${datafaker_em} | ${javafaker_em} |
| streetAddress | ${krandom_sa} | ${datafaker_sa} | ${javafaker_sa} |

SCALAR
fi

if [ -n "$OBJECT_LINES" ]; then
    krandom_obj=$(format_score "$OBJECT_LINES" "CompetitorObjectBenchmark.krandomObject")
    datafaker_obj=$(format_score "$OBJECT_LINES" "CompetitorObjectBenchmark.dataFakerObject")
    easyrandom_obj=$(format_score "$OBJECT_LINES" "CompetitorObjectBenchmark.easyRandomObject")
    instancio_obj=$(format_score "$OBJECT_LINES" "CompetitorObjectBenchmark.instancioObject")

    cat >> "${DASHBOARD}" << OBJECT
## Competitor Comparison: Object Population

Populate a 6-field POJO per invocation (ops/s, higher is better).

| Benchmark | krandom | DataFaker | EasyRandom | Instancio |
|:---|---:|---:|---:|---:|
| single object | ${krandom_obj} | ${datafaker_obj} | ${easyrandom_obj} | ${instancio_obj} |

OBJECT
fi

if [ -n "$BULK_LINES" ]; then
    krandom_100=$(format_score "$BULK_LINES" "CompetitorBulkBenchmark.krandomBulk" "100")
    datafaker_100=$(format_score "$BULK_LINES" "CompetitorBulkBenchmark.dataFakerBulk" "100")
    easyrandom_100=$(format_score "$BULK_LINES" "CompetitorBulkBenchmark.easyRandomBulk" "100")
    instancio_100=$(format_score "$BULK_LINES" "CompetitorBulkBenchmark.instancioBulk" "100")
    krandom_1k=$(format_score "$BULK_LINES" "CompetitorBulkBenchmark.krandomBulk" "1000")
    datafaker_1k=$(format_score "$BULK_LINES" "CompetitorBulkBenchmark.dataFakerBulk" "1000")
    easyrandom_1k=$(format_score "$BULK_LINES" "CompetitorBulkBenchmark.easyRandomBulk" "1000")
    instancio_1k=$(format_score "$BULK_LINES" "CompetitorBulkBenchmark.instancioBulk" "1000")

    cat >> "${DASHBOARD}" << BULK
## Competitor Comparison: Bulk Generation

Generate N objects per invocation (ops/s, higher is better).

| Batch size | krandom | DataFaker | EasyRandom | Instancio |
|:---|---:|---:|---:|---:|
| 100 | ${krandom_100} | ${datafaker_100} | ${easyrandom_100} | ${instancio_100} |
| 1,000 | ${krandom_1k} | ${datafaker_1k} | ${easyrandom_1k} | ${instancio_1k} |

BULK
fi

# ── Internal benchmarks ──────────────────────────────────────────────────────

INTERNAL_LINES=$(grep -v "Competitor" "${RAW_OUTPUT}" 2>/dev/null | grep -E "thrpt" || true)

if [ -n "$INTERNAL_LINES" ]; then
    cat >> "${DASHBOARD}" << 'INTERNAL_HEADER'
## Internal Benchmarks

krandom's own generator throughput across configurations.

```
INTERNAL_HEADER

    echo "$INTERNAL_LINES" >> "${DASHBOARD}"

    cat >> "${DASHBOARD}" << 'INTERNAL_FOOTER'
```

INTERNAL_FOOTER
fi

# ── Footer ────────────────────────────────────────────────────────────────────

cat >> "${DASHBOARD}" << FOOTER
## Raw Output

Full JMH output: [\`results/${TODAY}.txt\`](results/${TODAY}.txt)

## Reproducing

\`\`\`bash
# Full run (all benchmarks, ~10 min)
./scripts/run_benchmarks.sh

# Quick run (fewer iterations, ~3 min)
./scripts/run_benchmarks.sh --quick

# Competitor benchmarks only
./scripts/run_benchmarks.sh --competitor
\`\`\`

Requires Java 21+. Set \`JAVA_HOME\` if your default JDK differs.
FOOTER

step "Dashboard written to ${DASHBOARD}"
echo "  View: docs/benchmarks/DASHBOARD.md"
