    private PhoneNumberLayouts() {
    }

    /**
     * Returns the layouts of {@code country}, or {@code null} when the country has a dedicated
     * formatting method in {@link PhoneNumberGenerator}.
     */
    static Plan forCountry(String country) {
        return PLANS.get(country);
    }

    private static Map.Entry<String, Plan> plan(String country,
                                                List<FormatTemplate> landline,
                                                List<FormatTemplate> mobile) {
        return Map.entry(country, new Plan(landline, mobile));
    }

    /**
     * Landline and mobile layouts of one country; a country without a distinction lists the same
     * layouts twice.
     *
     * @param landline landline layouts
     * @param mobile   mobile layouts
     */
    record Plan(List<FormatTemplate> landline, List<FormatTemplate> mobile) {

        String generate(Random random, boolean formatted, boolean mobileNumber) {
            List<FormatTemplate> layouts = mobileNumber ? mobile() : landline();
            return layouts.get(random.nextInt(layouts.size())).render(random, formatted);
        }
    }
