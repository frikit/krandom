    static Stream<Arguments> phoneCases() {
        return withSameBranchKeys(PHONE);
    }

    static Stream<Arguments> msisdnCases() {
        return MSISDN.stream().map(golden -> Arguments.of(golden.localeKey(), golden.seed(), golden.expected()));
    }

    static Stream<Arguments> postalCases() {
        return withSameBranchKeys(POSTAL);
    }

    private static Stream<Arguments> withSameBranchKeys(List<Golden> goldens) {
        List<Arguments> cases = new ArrayList<>();
        for (Golden golden : goldens) {
            cases.add(Arguments.of(golden.localeKey(), golden.seed(), golden.expected()));
            for (String sameBranchKey : SAME_BRANCH_KEYS.get(golden.localeKey())) {
                cases.add(Arguments.of(sameBranchKey, golden.seed(), golden.expected()));
            }
        }
        return cases.stream();
    }

    private static GeneratorConfig config(String localeKey, long seed) {
        String[] parts = localeKey.split("_");
        Locale locale = parts.length == 1 ? Locale.of(parts[0]) : Locale.of(parts[0], parts[1]);
        return GeneratorConfig.builder().locale(locale).seed(seed).build();
    }

